//! Periodic B-spline forcing: uniform knots wrapped onto one period.
//!
//! With `dx = period / n_basis`, the unfolded basis has uniform knots at
//! integer multiples of `dx`. At `x = t mod period` in the interval
//! `[j·dx, (j+1)·dx)` the nonzero unfolded basis functions are `j … j + p`,
//! with the cardinal values `N_r((x − j·dx)/dx)` from
//! [`crate::bspline::cardinal_span`]. Folding identifies unfolded index `i`
//! with `i mod n_basis`, so the basis is periodic and sums to one; the centring
//! shift `s = (p − 1) div 2` then labels folded index `i` as coefficient
//! `(i − s) mod n_basis`, so basis 0 is centred on t = 0 (the convention of
//! pomp's `periodic_bspline_basis`; Wand & Ormerod 2008 §3). Hence
//!
//! f(t) = Σ_{r=0}^{p} N_r · c_{(j + r − s) mod n_basis},
//!
//! and `p < n_basis` makes the `p + 1` indices distinct, so no two terms fold
//! onto one coefficient. One call evaluates `p + 1` coefficients and
//! allocates nothing.
//!
//! Sources: de Boor (1978) *A Practical Guide to Splines*, ch. X (the
//! recurrence and the periodic construction); Piegl & Tiller (1997)
//! Algorithm A2.2 (the triangle); Eilers & Marx (1996) §2 (the wrap-fold).
//!
//! Oracles: `tests/fixtures/periodic_bspline_{scipy,pomp}.tsv` (degree 3) and
//! `periodic_bspline_degrees_scipy.tsv` (degrees 0–5), regenerated by
//! `make fixtures-bspline`, matched to 1e-12. Design:
//! `docs/dev/proposals/2026-10-27-estimable-bsplines.md` §4.2.

use crate::bspline::{cardinal_span, MAX_DEGREE};

/// The structural part of a periodic spline — period, basis count, degree —
/// checked once. Coefficients are supplied per evaluation.
#[derive(Debug, Clone, PartialEq)]
pub struct PeriodicBasis {
    period: f64,
    n_basis: usize,
    degree: usize,
    dx: f64,
    shift: usize,
}

impl PeriodicBasis {
    /// Refuses a non-finite or non-positive period, `n_basis ≤ degree`, and a
    /// degree above [`MAX_DEGREE`].
    pub fn new(period: f64, n_basis: usize, degree: usize) -> Result<Self, String> {
        if !(period.is_finite() && period > 0.0) {
            return Err(format!("period must be positive and finite, got {period}"));
        }
        if n_basis <= degree {
            return Err(format!("n_basis ({n_basis}) must exceed degree ({degree})"));
        }
        if degree > MAX_DEGREE {
            return Err(format!("degree ({degree}) must be at most {MAX_DEGREE}"));
        }
        Ok(PeriodicBasis {
            period,
            n_basis,
            degree,
            dx: period / n_basis as f64,
            shift: degree.saturating_sub(1) / 2,
        })
    }

    pub fn n_basis(&self) -> usize {
        self.n_basis
    }

    /// f(t) = Σₖ cₖ Bₖ(t), reading coefficient `k` through `coef(k)` for the
    /// `p + 1` indices nonzero at `t` only.
    #[inline]
    pub fn eval(&self, t: f64, mut coef: impl FnMut(usize) -> f64) -> f64 {
        let (j, n) = self.span(t);
        let nb = self.n_basis;
        let mut sum = 0.0;
        for (r, &v) in n.iter().enumerate().take(self.degree + 1) {
            sum += v * coef((j + r + nb - self.shift) % nb);
        }
        sum
    }

    /// Basis function `k`, Bₖ(t) = ∂f/∂cₖ: the same span as [`Self::eval`],
    /// so the value and its coefficient derivative cannot disagree. Zero when
    /// `k` is not among the `p + 1` coefficients nonzero at `t`.
    #[inline]
    pub fn basis(&self, t: f64, k: usize) -> f64 {
        let (j, n) = self.span(t);
        let nb = self.n_basis;
        (0..=self.degree)
            .find(|r| (j + r + nb - self.shift) % nb == k)
            .map_or(0.0, |r| n[r])
    }

    /// The interval j holding t mod period, and the `p + 1` cardinal values on it.
    #[inline]
    fn span(&self, t: f64) -> (usize, [f64; MAX_DEGREE + 1]) {
        let nb = self.n_basis;
        let mut x = t.rem_euclid(self.period);
        // rem_euclid can round up to exactly `period` for a tiny negative t.
        if x >= self.period {
            x -= self.period;
        }
        // `as usize` saturates: a NaN t gives j = 0 and a NaN value.
        let mut j = ((x / self.dx).floor() as usize).min(nb - 1);
        // Settle against the knots themselves, as `bspline::Knots::interval`
        // does, so the position u within the interval is in [0, 1].
        if j + 1 < nb && x >= (j + 1) as f64 * self.dx {
            j += 1;
        } else if j > 0 && x < j as f64 * self.dx {
            j -= 1;
        }
        (j, cardinal_span(self.degree, (x - j as f64 * self.dx) / self.dx))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn eval(b: &PeriodicBasis, t: f64, c: &[f64]) -> f64 {
        b.eval(t, |k| c[k])
    }

    /// Partition of unity at every degree: all coefficients 1 sum to 1.
    #[test]
    fn partition_of_unity() {
        for p in 0..=MAX_DEGREE {
            let b = PeriodicBasis::new(4.0, 7, p).unwrap();
            let ones = vec![1.0; 7];
            for i in 0..10_000 {
                let t = -8.0 + 16.0 * i as f64 / 9_999.0;
                let v = eval(&b, t, &ones);
                assert!((v - 1.0).abs() <= 1e-14, "p={p} t={t}: {v}");
            }
        }
    }

    /// Periodicity: f(t) = f(t ± period).
    #[test]
    fn periodicity() {
        let b = PeriodicBasis::new(4.0, 6, 3).unwrap();
        let c = [0.7, 1.2, 0.9, 0.5, 1.1, 0.8];
        for t in [0.123_f64, 1.5, 2.9, 3.6] {
            let a = eval(&b, t, &c);
            assert!((a - eval(&b, t + 4.0, &c)).abs() < 1e-12, "t={t}");
            assert!((a - eval(&b, t - 4.0, &c)).abs() < 1e-12, "t={t}");
        }
    }

    /// Degree 0 is a step function: bin j holds coefficient j (no shift).
    #[test]
    fn degree_zero_step_function() {
        let b = PeriodicBasis::new(4.0, 4, 0).unwrap();
        let c = [1.0, 2.0, 3.0, 4.0];
        for (t, want) in [(0.5, 1.0), (1.0, 2.0), (1.5, 2.0), (2.5, 3.0), (3.5, 4.0), (4.0, 1.0)] {
            assert_eq!(eval(&b, t, &c), want, "t={t}");
        }
    }

    /// Degree 0 at an exact knot takes the bin the knot opens, which only the
    /// knot comparison decides: `(j·dx)/dx` rounds below `j` for some bases.
    /// A tiny negative t wraps to bin 0, not to the end of the last bin.
    #[test]
    fn degree_zero_at_every_knot_and_at_the_wrap() {
        for period in [1.0, 4.0, 7.0, 365.25, 0.3] {
            for nb in 1..40 {
                let b = PeriodicBasis::new(period, nb, 0).unwrap();
                let c: Vec<f64> = (0..nb).map(|k| k as f64).collect();
                let dx = period / nb as f64;
                for j in 0..nb {
                    assert_eq!(eval(&b, j as f64 * dx, &c), j as f64, "period={period} nb={nb} knot {j}");
                }
                assert_eq!(eval(&b, -1e-300, &c), 0.0, "period={period} nb={nb}: wrap of a tiny negative t");
            }
        }
    }

    /// Only the p + 1 coefficients nonzero at t are read.
    #[test]
    fn reads_only_the_nonzero_coefficients() {
        for p in 0..=MAX_DEGREE {
            let b = PeriodicBasis::new(10.0, 9, p).unwrap();
            let mut reads = 0;
            b.eval(3.3, |_| {
                reads += 1;
                1.0
            });
            assert_eq!(reads, p + 1, "p={p}");
        }
    }

    #[test]
    fn malformed_bases_are_refused() {
        assert!(PeriodicBasis::new(0.0, 6, 3).is_err());
        assert!(PeriodicBasis::new(f64::NAN, 6, 3).is_err());
        assert!(PeriodicBasis::new(4.0, 3, 3).is_err());
        assert!(PeriodicBasis::new(4.0, 9, MAX_DEGREE + 1).is_err());
    }
}
